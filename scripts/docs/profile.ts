// Writes docs/src/rook-profile.js: the demo rook's cross-section profile
// along Z, computed exactly as auto-split does, for the auto-split chart.
//   npx tsx scripts/docs/profile.ts
import Module from 'manifold-3d';
import { readFileSync, writeFileSync } from 'fs';
import { parseSTL } from '../../src/core/stl';
import { weld } from '../../src/core/mesh';
import { toManifold } from '../../src/core/ops';
import { autoSplit } from '../../src/core/autosplit';
import { protrusionReserve } from '../../src/core/connectors';

const w = await Module(); w.setup();
const solid = toManifold(w, weld(parseSTL(readFileSync('demo/rook.stl').buffer)));
const r = autoSplit(solid, { bed: [256, 256, 256], margin: 2, minPart: 20, reserve: protrusionReserve('peg', 20) });
const p = r.profiles.find((x) => x.axis === 2)!;
writeFileSync('docs/src/rook-profile.js',
  `// Cross-section area of the demo rook along Z (mm²), sampled the same way auto-split does.\n` +
  `// Generated by scripts/docs/profile.ts. Cuts chosen: ${r.cuts.map((c) => c.pos).join(', ')} mm.\n` +
  `window.PROFILE = ${JSON.stringify({ lo: p.lo, hi: p.hi, areas: p.areas.map(Math.round) })};\n`);
console.log('cuts', r.cuts);
